// Copies the shared game code (engine, content packs, achievements) into
// supabase/functions/_game so the `game` Edge Function runs the exact same
// matching and dealing logic as the browser. Run before serving or deploying
// functions: `npm run functions:sync`. The output is generated; don't edit it.

import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = `${root}supabase/functions/_game`;

rmSync(out, { recursive: true, force: true });
mkdirSync(`${out}/data/packs`, { recursive: true });
cpSync(`${root}src/engine`, `${out}/engine`, { recursive: true });
cpSync(`${root}src/data/types.ts`, `${out}/data/types.ts`);
cpSync(`${root}src/achievements.ts`, `${out}/achievements.ts`);

const packs = readdirSync(`${root}src/data/packs`).filter((f) => f.endsWith('.ts') && !['index.ts', 'bundled.ts', 'none.ts'].includes(f));
for (const f of packs) cpSync(`${root}src/data/packs/${f}`, `${out}/data/packs/${f}`);

// Theme order comes from the client's pack index so both sides agree.
const index = readFileSync(`${root}src/data/packs/index.ts`, 'utf8');
const order = JSON.parse(index.match(/THEME_ORDER = (\[[^\]]*\])/)[1].replace(/'/g, '"'));
const ids = packs.map((f) => f.slice(0, -3));

writeFileSync(
  `${out}/packs.ts`,
  `// Generated by scripts/sync-functions.mjs — do not edit.\n` +
    ids.map((id, i) => `import p${i} from './data/packs/${id}.ts';`).join('\n') +
    `\nimport type { PackSpec } from './data/types.ts';\n\n` +
    `export const SPECS: PackSpec[] = [${ids.map((_, i) => `p${i}`).join(', ')}];\n` +
    `export const THEMES: string[] = ${JSON.stringify(order.filter((id) => ids.includes(id)))};\n`,
);
console.log(`synced engine + ${ids.length} packs → supabase/functions/_game`);
