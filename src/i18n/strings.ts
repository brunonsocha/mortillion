export function detectLang(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.slice(0, 2).toLowerCase();
    if (base === 'pl') return 'pl';
    if (base === 'uk' || base === 'ru' || base === 'be') return 'uk';
    if (base === 'en') return 'en';
  }
  return 'en';
}
