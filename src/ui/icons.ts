const urls = new Map<string, string>();

export function icon(name: keyof typeof ICONS | string): string {
  const sprite = ICONS[name] ?? ICONS.sealed;
  let u = urls.get(name);
  if (!u) {
    u = bake(sprite).toDataURL();
    urls.set(name, u);
  }
  return u;
}
