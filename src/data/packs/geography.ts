type CC = keyof typeof C;
type Answers = Record<Tier, CC[]>;

const names = (spec: string) => spec.split('|').filter(Boolean);

/**
 * A prompt whose answers are countries. Every other country in the table is
 * added to `reject`, so a near-miss like "Australia" for "Austria" or
 * "Iran" for "Iraq" is never fuzzy-matched into a valid answer.
 */
function countries(id: string, q: L10n, tiers: Answers, extraReject: string[] = []): PromptSpec {
  const valid = new Set<CC>(Object.values(tiers).flat());
  const validKeys = new Set([...valid].flatMap((c) => names(C[c])).map(matchKey));
  const reject = (Object.keys(C) as CC[])
    .filter((c) => !valid.has(c))
    .flatMap((c) => names(C[c]))
    .filter((n) => !validKeys.has(matchKey(n)));
  const answers = Object.fromEntries(
    Object.entries(tiers).map(([t, list]) => [t, list.map((c) => C[c])]),
  ) as Record<Tier, string[]>;
  return { id, q, answers, reject: [...new Set([...reject, ...extraReject])] };
}

