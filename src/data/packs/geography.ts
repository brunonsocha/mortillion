// Conventions used throughout this pack
//
// * "Country" = sovereign state. Disputed states are handled inclusively and
//   consistently: Kosovo, Taiwan, Palestine and Western Sahara (SADR) are
//   accepted wherever they fit geographically / by the prompt's criterion.
// * Transcontinental states are accepted on every continent they touch:
//   Europe includes Russia, Turkey, Kazakhstan, Georgia, Azerbaijan, Armenia
//   and Cyprus; Asia includes those plus Egypt (Sinai).
// * North America includes Central America and the Caribbean.
// * Landlocked uses the standard definition (Caspian states count as
//   landlocked).
// * England / Scotland / Wales are accepted as aliases of the United Kingdom.
// * Spoken-language prompts: Spanish/Arabic = countries where the language is
//   official (de jure or de facto). French = official as of 2020 (so Mali,
//   Burkina Faso and Niger count despite later demotion to 'working
//   language') plus Morocco, Tunisia, Algeria, Lebanon and Mauritius, where
//   French is widely used in administration and education.
// ---------------------------------------------------------------------------

